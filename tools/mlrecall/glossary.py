"""English–Vietnamese glossary from d2l-vi (`glossary.md`, CC BY-SA 4.0).

`mlr glossary` downloads the file at the commit pinned for `d2l-vi` in sources.yaml and writes
src/content/glossary.yaml (shown at /glossary/ and used by the Vietnamese UI);
`mlr glossary --check` fails when that file is out of date.
"""

from __future__ import annotations

import re
from io import StringIO

from ruamel.yaml import YAML

from . import bank, paths
from .importers.common import fetch

SOURCE_ID = "d2l-vi"
REPO = "d2l-ai/d2l-vi"
OUT = paths.CONTENT / "glossary.yaml"
_LINK_RE = re.compile(r"\[([^\]]*)\]\([^)]*\)")


def parse(markdown: str) -> list[dict[str, str]]:
    """Rows `| English | Tiếng Việt | … |` of the glossary tables, sorted by English term."""
    terms: dict[str, str] = {}
    for line in markdown.splitlines():
        line = line.strip()
        if not line.startswith("|") or set(line) <= set("|-: "):
            continue
        cells = [_LINK_RE.sub(r"\1", c).strip() for c in line.strip("|").split("|")]
        if len(cells) < 2 or cells[0] in ("English", "") or not cells[1]:
            continue
        terms.setdefault(cells[0], cells[1])
    return [{"en": en, "vi": vi} for en, vi in sorted(terms.items(), key=lambda t: sort_key(t[0]))]


def sort_key(term: str) -> str:
    """Alphabetical by the term itself: a leading "(model) " qualifier is skipped."""
    return re.sub(r"^\([^)]*\)\s*", "", term).lower()


def render(pinned: str, terms: list[dict[str, str]]) -> str:
    yaml = YAML()
    yaml.width = 4096
    yaml.allow_unicode = True
    buf = StringIO()
    yaml.dump({"source": SOURCE_ID, "pinned": pinned, "terms": terms}, buf)
    header = (
        f"# Generated by `uv run mlr glossary` from {REPO} glossary.md at {pinned[:12]}\n"
        "# (CC BY-SA 4.0, see THIRD_PARTY_NOTICES.md). Do not edit by hand.\n"
    )
    return header + buf.getvalue()


def run(check: bool = False) -> int:
    source = next(s for s in bank.load_sources().sources if s.id == SOURCE_ID)
    if not source.pinned:
        print(f"{SOURCE_ID}: no pinned commit in sources.yaml")
        return 1
    url = f"https://raw.githubusercontent.com/{REPO}/{source.pinned}/glossary.md"
    path = fetch(SOURCE_ID, source.pinned, "glossary.md", url)
    terms = parse(path.read_text(encoding="utf-8"))
    text = render(source.pinned, terms)
    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(paths.ROOT)} is out of date: run `uv run mlr glossary`")
            return 1
        print(f"{OUT.relative_to(paths.ROOT)}: up to date ({len(terms)} terms)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(paths.ROOT)} ({len(terms)} terms)")
    return 0
