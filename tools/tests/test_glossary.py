from mlrecall.glossary import parse, render, sort_key

SAMPLE = """# Bảng thuật ngữ

## A
| English          | Tiếng Việt     | Thảo luận tại                                |
|------------------|----------------|----------------------------------------------|
| accuracy         | độ chính xác   |                                              |
| (model) checkpoint | checkpoint (của mô hình) | [https://git.io/x](https://git.io/x) |
| Adam             | Adam           |                                              |
| accuracy         | duplicate      |                                              |
"""


def test_parse_rows_sorted_without_qualifiers():
    terms = parse(SAMPLE)
    assert [t["en"] for t in terms] == ["accuracy", "Adam", "(model) checkpoint"]
    assert terms[0]["vi"] == "độ chính xác"  # first occurrence wins
    assert sort_key("(strictly) convex function") == "convex function"


def test_render_is_yaml_with_header():
    text = render("abc123", parse(SAMPLE))
    assert text.startswith("# Generated by `uv run mlr glossary`")
    assert "pinned: abc123" in text
    assert "vi: độ chính xác" in text
